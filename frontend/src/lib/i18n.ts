const RTL_LANGS = new Set(["ar", "he", "fa", "ur"]);
export function getDirection(locale: string): "ltr" | "rtl" {
  return RTL_LANGS.has(locale.split("-")[0].toLowerCase()) ? "rtl" : "ltr";
}

