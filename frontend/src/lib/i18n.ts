/** Translate a known validation message; unknown (e.g. server-provided) messages pass through unchanged. */
export function translateError(message: string | undefined): string | undefined {
  if (!message) return message;
  const key = VALIDATION_KEYS[message];
  return key ? t(key) : message;
}
