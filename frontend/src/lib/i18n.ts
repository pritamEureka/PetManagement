export const catalogs: Record<Locale, Catalog> = { en, bn };

export type TranslateVars = Record<string, string | number>;

/** Pure translate: locale catalog -> English fallback -> key. Replaces {var} placeholders. */
export function translate(locale: Locale, key: string, vars?: TranslateVars): string {
  const template = catalogs[locale]?.[key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in vars ? String(vars[name]) : m,
  );
}

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && (SUPPORTED_LOCALES as readonly string[]).includes(v);
}

/** Reflects locale onto <html lang dir>. Safe to call outside a browser. */
export function applyDocumentLocale(locale: Locale): void {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale;
  document.documentElement.dir = getDirection(locale);
}

function detectInitialLocale(): Locale {
  if (typeof navigator !== "undefined") {
    const short = navigator.language?.split("-")[0];
    if (isLocale(short)) return short;
  }
  return DEFAULT_LOCALE;
}

interface LocaleState {
  locale: Locale;
  setLocale: (l: Locale) => void;
}

export const useLocaleStore = create<LocaleState>()(
  persist(
    (set) => ({
      locale: detectInitialLocale(),
      setLocale: (locale) => {
        if (!isLocale(locale)) return;
        applyDocumentLocale(locale);
        set({ locale });
      },
    }),
    {
      name: "pawzaroo-locale",
      partialize: (s) => ({ locale: s.locale }),
      onRehydrateStorage: () => (state) => {
        if (state) applyDocumentLocale(state.locale);
      },
    },
  ),
);

/** Non-hook translate using the current store locale (for non-React code). */
export function t(key: string, vars?: TranslateVars): string {
  return translate(useLocaleStore.getState().locale, key, vars);
}

export function useI18n() {
  const locale = useLocaleStore((s) => s.locale);
  const setLocale = useLocaleStore((s) => s.setLocale);
  useEffect(() => {
    applyDocumentLocale(locale);
  }, [locale]);
  return {
    locale,
    dir: getDirection(locale),
    setLocale,
    t: (key: string, vars?: TranslateVars) => translate(locale, key, vars),
  };
}

